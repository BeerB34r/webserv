#ifndef PARSER_HPP
# define PARSER_HPP

#include <functional>
#include <optional>
#include <string>
#include <utility>

template <typename T>
using Maybe = std::optional<T>;

template <typename T>
class Parser {
public:
	using resultType = std::pair<std::string,T>;

	Parser() = delete;
	Parser(std::function<Maybe<resultType>(const std::string&)>);
	Parser(const Parser&) = default;
	Parser&	operator =(const Parser&) = default;
	virtual	~Parser() = default;


	Maybe<resultType>	runParser(const std::string& s);
	Maybe<resultType>	operator()(const std::string& s);
private:
	std::function<Maybe<resultType>(const std::string&)>	f;
	/*Maybe<resultType>	(*f)(const std::string&);*/
};

namespace Parse {
	Parser<char>	parseChar(char c);
	Parser<char>	parseAny();
}

#include "Parser.tpp" // implementation

#endif // PARSER_HPP
