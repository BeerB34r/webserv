#include <cgi.hpp>
#include <unistd.h>

namespace cgi {
	auto	run(Server& self, std::string& bin) -> HTTPMessage {
		const pid_t	pid = fork();
		char	*cmdline[] = {
			bin.data(),
			NULL
		};
		const char	*env[] = { NULL };

		if (pid < 0)
			return self.statusPages.at(500);
		if (pid) { // parent
		}
		// child
		execve(bin.data(), cmdline, env);
	}
}
